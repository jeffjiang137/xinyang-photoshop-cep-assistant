class RuntimeError extends Error {
  constructor(code, message, details) {
    super(message || code);
    this.name = 'RuntimeError';
    this.code = code;
    this.details = details || {};
  }
}

function asRuntimeError(error, fallbackCode, fallbackMessage) {
  if (error instanceof RuntimeError) return error;
  const message = error && error.message ? error.message : String(error || fallbackMessage || fallbackCode);
  return new RuntimeError(error && error.code ? error.code : fallbackCode, message, {
    cause: error && error.stack ? error.stack : undefined
  });
}

